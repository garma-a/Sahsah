export const POINTS = [200, 200, 400, 400, 600, 600] as const

export type Question = {
  id: string
  categoryId: string
  row: 0 | 1 | 2 | 3 | 4 | 5
  points: 200 | 400 | 600
  prompt: string
  correctAnswer: string
  state: 'available' | 'answered'
}

export function buildQuestions(categoryIds: string[]): Question[] {
  return categoryIds.flatMap((cid) =>
    BANK[cid].map(([prompt, correctAnswer], i) => ({
      id: `${cid}-${i}`,
      categoryId: cid,
      row: i as Question['row'],
      points: POINTS[i],
      prompt,
      correctAnswer,
      state: 'available' as const,
    })),
  )
}

