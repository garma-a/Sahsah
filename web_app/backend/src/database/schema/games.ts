export const games = t.pgTable("games", {
  id: t.uuid("id").primaryKey().notNull(),
  roomId: t.uuid("room_id").notNull(),
  sequenceNumber: t.integer("sequence_number").notNull(),
  status: gameStatus("status").default("active").notNull(),
  stateVersion: t.bigint("state_version", { mode: "bigint" }).default(sql`0`).notNull(),
  startRequestId: t.uuid("start_request_id").unique().notNull(),
  startRequestDigest: bytea("start_request_digest").notNull(),
  startedAt: t.timestamp("started_at", { withTimezone: true, mode: "string" }).notNull(),
  endedAt: t.timestamp("ended_at", { withTimezone: true, mode: "string" }),
  endReason: gameEndReason("end_reason"),
  lastGameplayAt: t.timestamp("last_gameplay_at", { withTimezone: true, mode: "string" }).notNull(),
  idleExpiresAt: t.timestamp("idle_expires_at", { withTimezone: true, mode: "string" }).notNull(),
  firstQuestionOpenedAt: t.timestamp("first_question_opened_at", { withTimezone: true, mode: "string" }),
  contentPurgeAfter: t.timestamp("content_purge_after", { withTimezone: true, mode: "string" }),
  contentPurgedAt: t.timestamp("content_purged_at", { withTimezone: true, mode: "string" }),
  hostAccountId: t.uuid("host_account_id").notNull(),
  teamOneName: t.text("team_one_name").notNull(),
  teamTwoName: t.text("team_two_name").notNull(),
  teamOneScore: t.bigint("team_one_score", { mode: "bigint" }).default(sql`0`).notNull(),
  teamTwoScore: t.bigint("team_two_score", { mode: "bigint" }).default(sql`0`).notNull(),
  activeBoardPosition: t.smallint("active_board_position"),
  activeQuestionPosition: t.smallint("active_question_position"),
  controllerGeneration: t.bigint("controller_generation", { mode: "bigint" }).default(sql`1`).notNull(),
  controllerCredentialHash: bytea("controller_credential_hash").notNull(),
  controllerAcquiredAt: t.timestamp("controller_acquired_at", { withTimezone: true, mode: "string" }).notNull(),
}, (table): t.PgTableExtraConfigValue[] => [
  t.uniqueIndex("games_room_membership_identity").on(table.id, table.roomId),
  t.uniqueIndex("games_room_sequence").on(table.roomId, table.sequenceNumber),
  t.uniqueIndex("games_host_identity").on(table.id, table.hostAccountId),
  t.uniqueIndex("games_one_active_per_room").on(table.roomId).where(sql`status = 'active'`),
  t.index("games_due_expiry").on(table.idleExpiresAt, table.id).where(sql`status = 'active'`),
  t.index("games_due_content_purge").on(table.contentPurgeAfter, table.id).where(sql`content_purged_at IS NULL AND content_purge_after IS NOT NULL`),
  t.foreignKey({
    name: "games_room_owner",
    columns: [table.roomId, table.hostAccountId],
    foreignColumns: [rooms.id, rooms.ownerAccountId],
  }).onDelete("no action").onUpdate("no action"),
  t.foreignKey({
    name: "games_current_question",
    columns: [table.id, table.activeBoardPosition, table.activeQuestionPosition],
    foreignColumns: [gameQuestions.gameId, gameQuestions.boardPosition, gameQuestions.questionPosition],
  }).onDelete("no action").onUpdate("no action"),
  t.check("games_positive_sequence", sql`sequence_number > 0`),
  t.check("games_nonnegative_version", sql`state_version >= 0`),
  t.check("games_start_request_digest_shape", sql`octet_length(start_request_digest) = 32`),
  t.check("games_terminal_time", sql`(status IN ('finished', 'expired', 'failed')) = (ended_at IS NOT NULL)`),
  t.check("games_end_reason_pair", sql`(ended_at IS NULL) = (end_reason IS NULL)`),
  t.check("games_activity_order", sql`last_gameplay_at >= started_at`),
  t.check("games_end_order", sql`ended_at IS NULL OR ended_at >= last_gameplay_at`),
  t.check("games_fixed_idle_window", sql`idle_expires_at = last_gameplay_at + interval '24 hours'`),
  t.check("games_reason_matches_state", sql`end_reason IS NULL OR (status = 'finished' AND end_reason IN ('completed', 'host_ended', 'host_left')) OR (status = 'expired' AND end_reason = 'idle_timeout') OR (status = 'failed' AND end_reason = 'platform_failure')`),
  t.check("games_effective_expiry_time", sql`status <> 'expired' OR ended_at = idle_expires_at`),
  t.check("games_first_open_time", sql`first_question_opened_at IS NULL OR (started_at IS NOT NULL AND first_question_opened_at >= started_at AND (ended_at IS NULL OR first_question_opened_at <= ended_at))`),
  t.check("games_completion_requires_opening", sql`end_reason IS DISTINCT FROM 'completed' OR first_question_opened_at IS NOT NULL`),
  t.check("games_content_retention_presence", sql`(ended_at IS NULL) = (content_purge_after IS NULL)`),
  t.check("games_content_retention_window", sql`content_purge_after IS NULL OR content_purge_after = ended_at + interval '12 months'`),
  t.check("games_content_purge_order", sql`content_purged_at IS NULL OR (content_purge_after IS NOT NULL AND content_purged_at >= content_purge_after)`),
  t.check("games_team_names", sql`length(btrim(team_one_name)) > 0 AND length(btrim(team_two_name)) > 0`),
  t.check("games_nonnegative_scores", sql`team_one_score >= 0 AND team_two_score >= 0`),
  t.check("games_active_pointer_pair", sql`(active_board_position IS NULL) = (active_question_position IS NULL)`),
  t.check("games_active_pointer_bounds", sql`active_board_position IS NULL OR (active_board_position BETWEEN 1 AND 6 AND active_question_position BETWEEN 1 AND 6)`),
  t.check("games_terminal_board", sql`status = 'active' OR active_board_position IS NULL`),
  t.check("games_controller_shape", sql`controller_generation > 0 AND octet_length(controller_credential_hash) = 32`),
  t.check("games_controller_acquisition", sql`controller_acquired_at >= started_at`),
]);

