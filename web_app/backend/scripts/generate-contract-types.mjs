import { readFileSync, writeFileSync } from "node:fs";
const root = new URL("../src/gameplay/contracts/", import.meta.url);
function type(schema, prefix) {
  if (schema === true) return "unknown";
  if (schema === false) return "never";
  const parts = [];
  if (schema.$ref) parts.push(`${prefix}[${JSON.stringify(schema.$ref.split("/").at(-1))}]`);
  if (schema.enum) parts.push(schema.enum.map((v) => JSON.stringify(v)).join(" | "));
  else if (schema.type === "array") parts.push(`(${type(schema.items, prefix)})[]`);
  else if (schema.type === "object" || schema.properties || schema.required) {
    const properties = { ...schema.properties };
    for (const key of schema.required ?? []) properties[key] ??= true;
    parts.push(`{ ${Object.entries(properties).map(([k, v]) => `${JSON.stringify(k)}${schema.required?.includes(k) ? "" : "?"}: ${type(v, prefix)}`).join("; ")} }`);
  } else if (schema.type) {
    parts.push([schema.type].flat().map((t) => ({ integer: "number", number: "number", string: "string", boolean: "boolean", null: "null" })[t] ?? (() => { throw new Error(`Unsupported type: ${t}`); })()).join(" | "));
  }
  if (schema.allOf) parts.push(schema.allOf.map((s) => `(${type(s, prefix)})`).join(" & "));
  for (const key of ["oneOf", "anyOf"]) if (schema[key]) parts.push(`(${schema[key].map((s) => `(${type(s, prefix)})`).join(" | ")})`);
  const result = parts.length ? parts.map((p) => `(${p})`).join(" & ") : "unknown";
  return schema.nullable ? `(${result}) | null` : result;
}
for (const [file, key, name, output] of [
  ["openapi.json", "components", "WireTypes", "wire-types.ts"],
  ["realtime.schema.json", "$defs", "RealtimeTypes", "realtime-types.ts"],
]) {
  const source = JSON.parse(readFileSync(new URL(file, root), "utf8"));
  const definitions = key === "components" ? source.components.schemas : source.$defs;
  const text = `// Generated by scripts/generate-contract-types.mjs from ${file}; do not edit.\n// AJV remains responsible for all runtime constraints and normalization.\nexport interface ${name} {\n${Object.entries(definitions).map(([k,v]) => `  ${k}: ${type(v, name)};`).join("\n")}\n}\n`;
  writeFileSync(new URL(output, root), text);
  if (name === "WireTypes") writeFileSync(new URL("schema-registry.ts", root),
    '// Generated by scripts/generate-contract-types.mjs; do not edit.\nimport type { ZodType } from "zod";\nimport type { WireTypes } from "./wire-types.js";\nexport function makeSchemas(factory: <T>(name: string) => ZodType<T>) {\n  return {\n' + Object.keys(definitions).map((name) => `    ${name}: factory<WireTypes[${JSON.stringify(name)}]>(${JSON.stringify(name)}),`).join("\n") + '\n  };\n}\n');
}
